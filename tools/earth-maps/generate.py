#!/usr/bin/env python3
"""
Generates the larger Earth maps (`Maps/Earth104x65.ts`, `Maps/Earth128x80.ts`) from Civilization's own 80 x 50 map,
and draws `preview.png` with each map and its start tiles. See README.md.
"""
import os
import sys

os.chdir(os.path.dirname(os.path.abspath(__file__)))

if not os.path.exists('ne_50m_land.geojson'):
    sys.exit('ne_50m_land.geojson is missing: see README.md.')

from collections import Counter
from civ1map import TERRAIN as CIV1, STARTS as CIV1_STARTS
from png import PAL, write_png
from upscale import upscale, draw_rivers, place_starts

SIZES = [(104, 65), (128, 80)]

# Hand edits on top of the generated maps: {size: {(x, y): terrain}}
OVERRIDES = {
    (104, 65): {
        (39, 18): 'G',  # Britain: extend the southern tip west (Cornwall)
    },
    (128, 80): {
        (48, 23): 'G',  # Britain: extend the southern tip west (Cornwall)
        # Iberia: one more row along the southern coast
        (48, 32): 'P', (49, 32): 'P', (50, 32): 'P', (51, 32): 'P', (52, 32): 'P',
        # Italy: the western hills by Rome become farmland
        (57, 29): 'G', (57, 30): 'P', (58, 30): 'G',
    },
}


def stats(rows):
    counts = Counter(''.join(rows))
    land = sum(v for k, v in counts.items() if k != 'O')
    return f"land {land / sum(counts.values()):.1%} " + ' '.join(
        f"{k}:{v / land:.1%}" for k, v in counts.most_common() if k != 'O')


def typescript(width, height, rows, starts):
    names = list(starts)
    lines = [
        'import {',
        *[f'  {name},' for name in names],
        "} from '@civ-clone/civ1-civilization/Civilizations';",
        "import EarthMap from '../EarthMap';",
        '',
        f'// Generated by tools/earth-maps/generate.py: Civilization\'s own Earth, scaled up to {width} x {height}.',
        f'export const earth{width}x{height}: EarthMap = {{',
        f'  width: {width},',
        f'  height: {height},',
        '  startTiles: [',
        *[f'    [{name}, {{ x: {x}, y: {y} }}],' for name, (x, y) in starts.items()],
        '  ],',
        '  terrain: `' + '\n'.join(rows) + '\n`,',
        '};',
        '',
        f'export default earth{width}x{height};',
        '',
    ]
    return '\n'.join(lines)


panels = [(CIV1, CIV1_STARTS)]

for width, height in SIZES:
    grid, _, _, added = upscale(width, height)
    draw_rivers(grid, width, height)

    for (x, y), terrain in OVERRIDES.get((width, height), {}).items():
        grid[y][x] = terrain

    rows = [''.join(row) for row in grid]
    starts = place_starts(rows, width, height)

    with open(os.path.join('..', '..', 'Maps', f'Earth{width}x{height}.ts'), 'w') as file:
        file.write(typescript(width, height, rows, starts))

    panels.append((rows, starts))
    print(f'{width} x {height}: {stats(rows)}')
    print(f'  islands added: {", ".join(f"{name} ({len(tiles)})" for name, tiles in added.items())}')

# one panel per map, the original first, start tiles in red
PW, PH, GAP = 896, 560, 12
SW, SH = PW + 2 * GAP, len(panels) * (PH + GAP) + GAP
image = [[(24, 24, 28)] * SW for _ in range(SH)]

for n, (rows, starts) in enumerate(panels):
    W, H = len(rows[0]), len(rows)
    ox, oy = GAP, GAP + n * (PH + GAP)

    for y in range(PH):
        row = rows[y * H // PH]

        for x in range(PW):
            image[oy + y][ox + x] = PAL[row[x * W // PW]]

    for i, j in starts.values():
        cx, cy = ox + int((i + .5) * PW / W), oy + int((j + .5) * PH / H)

        for dy in range(-4, 5):
            for dx in range(-4, 5):
                d = dx * dx + dy * dy

                if d <= 16:
                    image[cy + dy][cx + dx] = (230, 30, 30) if d <= 8 else (255, 255, 255)

write_png('preview.png', SW, SH, image)
